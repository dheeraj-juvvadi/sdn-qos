#!/usr/bin/env python3
"""Write experiments/results/RESULTS.md: tables generated from the CSV/JSON
results so the report never contains hand-typed numbers."""
import glob
import json
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "experiments", "results")
MAIN = ["baseline_bw10_f2", "static_bw10_f2", "adaptive_bw10_f2"]
ROWS = [
    ("voip_idle_lat_mean_ms", "VoIP delay, idle phase (ms)"),
    ("voip_congested_lat_mean_ms", "VoIP mean delay (ms)"),
    ("voip_congested_lat_p95_ms", "VoIP p95 delay (ms)"),
    ("voip_congested_lat_p99_ms", "VoIP p99 delay (ms)"),
    ("voip_congested_jitter_ms", "VoIP jitter RFC3550 (ms)"),
    ("voip_congested_loss_pct", "VoIP loss (%)"),
    ("video_congested_lat_mean_ms", "Video mean delay (ms)"),
    ("video_congested_lat_p95_ms", "Video p95 delay (ms)"),
    ("video_congested_jitter_ms", "Video jitter (ms)"),
    ("video_congested_loss_pct", "Video loss (%)"),
    ("video_congested_kbps", "Video goodput (kbit/s)"),
    ("bulk_congested_kbps", "Bulk throughput, congested (kbit/s)"),
    ("bulk_recovery_kbps", "Bulk throughput, recovery (kbit/s)"),
    ("bulk_congested_jain", "Jain fairness, bulk streams"),
    ("link_util_congested", "Bottleneck utilisation, congested"),
    ("packet_in_total", "PacketIn messages per run"),
    ("flow_setups", "Flow setups (classified) per run"),
    ("flow_setup_us_mean", "Controller flow-setup time (us)"),
    ("adaptation_events", "Adaptation events per run"),
]


def fmt(mean, ci):
    if pd.isna(mean):
        return "n/a"
    if pd.isna(ci):
        return "%.3g" % mean
    return "%.3g ± %.2g" % (mean, ci)


def main():
    summ = pd.read_csv(os.path.join(RES, "summary.csv"))
    runs = pd.read_csv(os.path.join(RES, "runs.csv"))
    out = ["# Results (generated by analysis/summarize.py)", ""]
    n = {c: int((runs.config == c).sum()) for c in MAIN}
    out += ["Main comparison: bottleneck 10 Mbit/s, 2 bulk TCP streams, congested phase "
            "unless noted. Values are mean ± 95%% CI over runs (n = %s)." %
            ", ".join("%s %d" % (c.split("_")[0], n[c]) for c in MAIN), ""]
    out += ["| Metric | Baseline | SDN-QoS static | SDN-QoS adaptive |", "|---|---|---|---|"]
    for m, label in ROWS:
        cells = []
        for c in MAIN:
            r = summ[(summ.config == c) & (summ.metric == m)]
            cells.append(fmt(r["mean"].iloc[0], r.ci95.iloc[0]) if len(r) else "n/a")
        out.append("| %s | %s |" % (label, " | ".join(cells)))
    tests = pd.read_csv(os.path.join(RES, "stats_tests.csv"))
    out += ["", "## Significance tests (baseline vs QoS)", "",
            "| QoS config | Metric | Baseline mean | QoS mean | Welch p | Mann-Whitney p |",
            "|---|---|---|---|---|---|"]
    for _, t in tests.iterrows():
        out.append("| %s | %s | %.3g | %.3g | %.2e | %.2e |" % (
            t.qos, t.metric, t.baseline_mean, t.qos_mean, t.welch_p, t.mannwhitney_p))
    sweep = runs[~runs.config.isin(["static_bw10_f2"]) & ~runs.config.str.endswith("_meteronly")]
    if sweep.config.nunique() > 2:
        out += ["", "## Sweep (mean over runs)", "",
                "| Config | n | VoIP p95 delay (ms) | VoIP loss (%) | Video loss (%) | "
                "Bulk congested (kbit/s) | Jain |", "|---|---|---|---|---|---|---|"]
        for cfg, g in sweep.groupby("config"):
            out.append("| %s | %d | %.3g | %.3g | %.3g | %.4g | %.3f |" % (
                cfg, len(g), g.voip_congested_lat_p95_ms.mean(), g.voip_congested_loss_pct.mean(),
                g.video_congested_loss_pct.mean(), g.bulk_congested_kbps.mean(),
                g.bulk_congested_jain.mean()))
    mo = runs[runs.config.str.endswith("_meteronly")]
    if len(mo):
        out += ["", "## Meter-only variant (R1 demonstration: no priority queues, bulk cap 9 Mbit/s)",
                "", "| Config | n | VoIP mean delay (ms) | VoIP p95 (ms) | Video loss (%) | "
                "Video mean delay (ms) | Bulk congested (kbit/s) | Adaptation events |",
                "|---|---|---|---|---|---|---|---|"]
        for cfg, g in mo.groupby("config"):
            out.append("| %s | %d | %.3g | %.3g | %.3g | %.3g | %.4g | %.3g |" % (
                cfg, len(g), g.voip_congested_lat_mean_ms.mean(),
                g.voip_congested_lat_p95_ms.mean(), g.video_congested_loss_pct.mean(),
                g.video_congested_lat_mean_ms.mean(), g.bulk_congested_kbps.mean(),
                g.adaptation_events.mean() if "adaptation_events" in g else float("nan")))
    ch = sorted(glob.glob(os.path.join(RES, "challenges", "*.json")))
    if ch:
        out += ["", "## Phase 9 challenge experiments (raw JSON)", ""]
        for path in ch:
            data = json.load(open(path))
            if isinstance(data, dict):
                data.pop("meter_features_s1", None)
            out += ["### %s" % os.path.basename(path)[:-5], "```json",
                    json.dumps(data, indent=1), "```", ""]
    demo = os.path.join(ROOT, "docs", "evidence", "rest_demo.txt")
    if os.path.exists(demo):
        out += ["## REST demo", "", "See docs/evidence/rest_demo.txt", ""]
    with open(os.path.join(RES, "RESULTS.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote experiments/results/RESULTS.md")


if __name__ == "__main__":
    main()
